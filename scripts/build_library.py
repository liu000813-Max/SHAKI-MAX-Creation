"""Build the unified real Product Library layers for the web app.

Sources (all REAL, no fabrication):
  1. brand     — apps/web/lib/data/products.ts (13 curated SHAKI SKUs, PM-categorised) -> kept in TS.
  2. candidate — data/processed/products.json (1439 crawled SHAKI.com SKUs, sparse)   -> slim JSON emitted here.
  3. asset     — apps/web/lib/data/heydildi-catalog.json (55 supplier SKUs, media only) -> kept as-is.

This script emits ONLY the slim candidate layer + a tiny stats file, so the UI can show the
layer breakdown without pulling the 776 KB candidate JSON into its bundle.
Commercial/attribute fields are copied verbatim from the crawl; nothing is invented.
"""
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "processed" / "products.json"
OUT = ROOT / "apps" / "web" / "lib" / "data" / "library-candidates.json"
STATS_OUT = ROOT / "apps" / "web" / "lib" / "data" / "library-stats.json"

# PRD TABLE 2 hard-filter gate (mirrors apps/web/lib/config/matching.ts).
GATE = 75

# Attributes the CRAWL itself can supply. Anything here that is still empty on a candidate
# row is a cheap win (re-scrape / tag), as opposed to the PM-side fields below.
CRAWL_FIELDS = [
    "name_en",
    "inferred_category",
    "secondary_category",
    "target_gender",
    "main_material",
    "primary_function",
    "hero_image_url",
    "intel_score",
]

# Fields the crawl structurally CANNOT produce — a PM must fill them for the row to score.
PM_REQUIRED_FIELDS = [
    "description",
    "key_selling_point",
    "target_age",
    "target_segment",
    "design_style",
    "visual_style",
    "price_level",
    "target_market",
    "oem_odm",
    "product_status",
    "ai_scores",
]

# Fields we surface for the candidate (asset/browse) layer.
KEEP = [
    "product_id",
    "product_name_en",
    "inferred_primary_category",
    "secondary_category",
    "target_gender",
    "main_material",
    "hero_image_url",
    "data_completeness",
]


def slim(p: dict) -> dict:
    f = p.get("fields") or {}
    raw_tags = p.get("tags") or []
    if not isinstance(raw_tags, list):
        raw_tags = []
    return {
        "product_id": p.get("product_id"),
        "sku": p.get("sku") or p.get("product_name_en") or p.get("product_id"),
        "name_en": p.get("product_name_en"),
        "name_cn": p.get("product_name_cn"),
        "layer": "candidate",
        "inferred_category": p.get("inferred_primary_category"),
        "secondary_category": p.get("secondary_category") or f.get("secondary_category"),
        "target_gender": p.get("target_gender") or f.get("target_gender"),
        "main_material": f.get("main_material"),
        "primary_function": f.get("primary_function"),
        "hero_image_url": p.get("hero_image_url"),
        "intel_score": f.get("product_intelligence_score"),
        "completeness": p.get("data_completeness") or 0,
        "eligible": bool(p.get("recommendation_eligible")),
        "media_count": len(p.get("media") or []),
        "tags": {
            "all": raw_tags,
            "category": f.get("category_tags") or [],
            "function": f.get("function_tags") or [],
            "audience": f.get("audience_tags") or [],
            "scenario": f.get("scenario_tags") or [],
        },
    }


def build_stats(rows: list[dict]) -> dict:
    """Layer breakdown + the enrichment queue (which crawled rows are closest to the gate)."""
    hero = ROOT / "apps" / "web" / "lib" / "data" / "heydildi-catalog.json"
    assets = json.loads(hero.read_text(encoding="utf-8")) if hero.exists() else []
    asset_count = len(assets)

    brand_count = 13  # apps/web/lib/data/products.ts — all 13 clear the gate at 100%.
    comp = [r["completeness"] for r in rows]

    def present(r: dict) -> list[str]:
        out = []
        for f in CRAWL_FIELDS:
            v = r.get(f)
            if v is None or v == "" or (isinstance(v, list) and not v):
                continue
            out.append(f)
        return out

    queue = []
    for r in sorted(rows, key=lambda x: (-len(present(x)), -(x["completeness"] or 0), x["product_id"])):
        p = present(r)
        queue.append(
            {
                "product_id": r["product_id"],
                "sku": r["sku"],
                "name_en": r["name_en"] or r["sku"],
                "name_cn": r["name_cn"],
                "category": r["inferred_category"] or "Unmapped",
                "completeness": r["completeness"],
                "hero_image_url": r["hero_image_url"],
                "evidence_count": len(p),
                "missing_crawl_fields": [f for f in CRAWL_FIELDS if f not in p],
            }
        )
        if len(queue) >= 24:
            break

    return {
        "_note": "Generated by scripts/build_library.py — do not edit by hand.",
        "gate": GATE,
        "total": brand_count + len(rows) + asset_count,
        "eligibleTotal": brand_count,
        "layers": [
            {
                "key": "brand",
                "zh": "自有货盘（已定稿）",
                "en": "Brand catalogue (curated)",
                "count": brand_count,
                "eligible": brand_count,
                "noteZh": "PM 已定稿的 SHAKI 自有 SKU，参数字段完整，直接进入评分池。",
                "noteEn": "PM-curated SHAKI SKUs with complete parameters; these score today.",
            },
            {
                "key": "candidate",
                "zh": "官网抓取货盘",
                "en": "Crawled catalogue",
                "count": len(rows),
                "eligible": 0,
                "noteZh": f"从 SHAKI.com 抓取的真实 SKU。字段稀疏（完整度最高 {max(comp) if comp else 0}%），补齐参数后可自动升入评分池。",
                "noteEn": f"Real SKUs crawled from SHAKI.com. Sparse (max completeness {max(comp) if comp else 0}%); auto-promotes once parameters are filled.",
            },
            {
                "key": "asset",
                "zh": "供应商媒体包",
                "en": "Supplier media packs",
                "count": asset_count,
                "eligible": 0,
                "noteZh": "只有图片 / 视频 / CAD，无任何商用参数——参数缺失即为缺失，不猜测。",
                "noteEn": "Media only (images / videos / CAD). No commercial parameters; nothing is guessed.",
            },
        ],
        "candidateCompletenessMax": max(comp) if comp else 0,
        "candidateByCategory": dict(Counter([r["inferred_category"] for r in rows])),
        "pmRequiredFields": PM_REQUIRED_FIELDS,
        "enrichmentQueue": queue,
    }


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    rows = [slim(p) for p in d["products"]]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(rows, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    comp = [r["completeness"] for r in rows]
    print("wrote:", OUT.relative_to(ROOT), "| rows:", len(rows), "| bytes:", OUT.stat().st_size)
    print("completeness: min", min(comp), "max", max(comp), "| eligible:", sum(1 for r in rows if r["eligible"]))
    print("by inferred_category:", dict(Counter([r["inferred_category"] for r in rows])))
    print("with hero_image_url:", sum(1 for r in rows if r["hero_image_url"]))

    stats = build_stats(rows)
    STATS_OUT.write_text(json.dumps(stats, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print("wrote:", STATS_OUT.relative_to(ROOT), "| bytes:", STATS_OUT.stat().st_size)


if __name__ == "__main__":
    main()
